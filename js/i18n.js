window.KSC_Lang = {
  get() {
    return localStorage.getItem("ksc_lang") || "vi";
  },
  set(lang) {
    localStorage.setItem("ksc_lang", lang);
  },
  t(key) {
    const lang = this.get();
    return (window.KSC_I18N[lang] && window.KSC_I18N[lang][key]) || window.KSC_I18N.vi[key] || key;
  },
  apply(root = document) {
    root.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      const val = this.t(key);
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        if (el.hasAttribute("data-i18n-placeholder")) el.placeholder = val;
      } else {
        el.textContent = val;
      }
    });
    root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.placeholder = this.t(el.getAttribute("data-i18n-placeholder"));
    });
    document.documentElement.lang = this.get() === "ja" ? "ja" : "vi";
  },
};
